// Core engine: pieces, rotation systems, randomizers and the frame-stepped game.
// DOM-free so it can run headlessly (see test/sim.js).
(function () {
'use strict';
const TGM = (globalThis.TGM = globalThis.TGM || {});

const parse = (s) => {
  const out = [];
  s.split('|').forEach((row, y) => [...row].forEach((ch, x) => { if (ch === 'X') out.push([x, y]); }));
  return out;
};
const boxSize = (t) => (t === 'I' || t === 'O' ? 4 : 3);

// ---- ARS (Classic rule). State 0 is the spawn state, state 1 is one CW turn.
const ARS_SRC = {
  I: ['....|XXXX|....|....', '..X.|..X.|..X.|..X.'],
  T: ['...|XXX|.X.', '.X.|XX.|.X.', '...|.X.|XXX', '.X.|.XX|.X.'],
  L: ['...|XXX|X..', 'XX.|.X.|.X.', '...|..X|XXX', '.X.|.X.|.XX'],
  J: ['...|XXX|..X', '.X.|.X.|XX.', '...|X..|XXX', '.XX|.X.|.X.'],
  S: ['...|.XX|XX.', 'X..|XX.|.X.'],
  Z: ['...|XX.|.XX', '..X|.XX|.X.'],
  O: ['....|.XX.|.XX.|....'],
};
const ARS = {};
for (const t in ARS_SRC) {
  const st = ARS_SRC[t].map(parse);
  ARS[t] = [0, 1, 2, 3].map((i) => st[i % st.length]);
}

// ---- SRS (World rule). Generated by rotating the spawn state about the box centre.
const SRS_SRC = {
  I: '....|XXXX|....|....', T: '.X.|XXX|...', L: '..X|XXX|...', J: 'X..|XXX|...',
  S: '.XX|XX.|...', Z: 'XX.|.XX|...', O: '.XX.|.XX.|....|....',
};
const SRS = {};
for (const t in SRS_SRC) {
  let cells = parse(SRS_SRC[t]);
  const n = boxSize(t);
  SRS[t] = [cells];
  for (let i = 1; i < 4; i++) {
    if (t !== 'O') cells = cells.map(([x, y]) => [n - 1 - y, x]);
    SRS[t].push(cells);
  }
}
// Kick tables are written in the usual x-right / y-up notation and flipped to y-down here.
const K = (s) => s.split(' ').map((p) => { const [x, y] = p.split(',').map(Number); return [x, y ? -y : 0]; });
const SRS_KICKS = {
  '01': K('0,0 -1,0 -1,1 0,-2 -1,-2'), '10': K('0,0 1,0 1,-1 0,2 1,2'),
  '12': K('0,0 1,0 1,-1 0,2 1,2'), '21': K('0,0 -1,0 -1,1 0,-2 -1,-2'),
  '23': K('0,0 1,0 1,1 0,-2 1,-2'), '32': K('0,0 -1,0 -1,-1 0,2 -1,2'),
  '30': K('0,0 -1,0 -1,-1 0,2 -1,2'), '03': K('0,0 1,0 1,1 0,-2 1,-2'),
};
// Arika's I-piece kicks (TGM3 World differs from guideline SRS here).
const SRS_KICKS_I = {
  '01': K('0,0 -2,0 1,0 1,2 -2,-1'), '10': K('0,0 2,0 -1,0 2,1 -1,-2'),
  '12': K('0,0 -1,0 2,0 -1,2 2,-1'), '21': K('0,0 -2,0 1,0 -2,1 1,-1'),
  '23': K('0,0 2,0 -1,0 2,1 -1,-1'), '32': K('0,0 1,0 -2,0 1,2 -2,-1'),
  '30': K('0,0 -2,0 1,0 -2,1 1,-2'), '03': K('0,0 2,0 -1,0 -1,2 2,-1'),
};

const RULES = {
  // TGM2: ARS with right/left wall kicks only.
  tap: { id: 'tap', name: 'CLASSIC', shapes: ARS, ars: true, ti: false, softLock: true, hardLock: false, moveReset: false, swap: false, colors: 'classic' },
  // TGM3 Classic: adds I wall kicks and I/T floor kicks.
  classic: { id: 'classic', name: 'CLASSIC', shapes: ARS, ars: true, ti: true, softLock: true, hardLock: false, moveReset: false, swap: false, colors: 'classic' },
  // TGM3 World: SRS, move reset, hard drop on up, rotation buttons swapped.
  world: { id: 'world', name: 'WORLD', shapes: SRS, ars: false, ti: true, softLock: false, hardLock: true, moveReset: true, swap: true, colors: 'world' },
};
const WORLD_MOVE_RESETS = 10;
const WORLD_ROT_RESETS = 8;

// ---- RNG and randomizers
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const TYPES = ['I', 'Z', 'S', 'J', 'L', 'O', 'T'];
const FIRST = ['I', 'J', 'L', 'T'];

// TGM2: 4-piece history, 6 tries.
function tapRandomizer(r) {
  const hist = ['Z', 'S', 'S', 'Z'];
  let first = true;
  return () => {
    let p;
    if (first) { first = false; p = FIRST[Math.floor(r() * 4)]; }
    else {
      for (let i = 0; i < 6; i++) { p = TYPES[Math.floor(r() * 7)]; if (!hist.includes(p)) break; }
    }
    hist.shift(); hist.push(p);
    return p;
  };
}

// TGM3: 35-piece pool, 4-piece history, 6 tries, drought-biased pool refill.
function tiRandomizer(r) {
  const pool = [];
  for (const t of TYPES) for (let i = 0; i < 5; i++) pool.push(t);
  const hist = ['S', 'Z', 'S', 'Z'];
  const order = [];
  let first = true;
  return () => {
    let p;
    if (first) { first = false; p = FIRST[Math.floor(r() * 4)]; }
    else {
      let i = 0;
      for (let roll = 0; roll < 6; roll++) {
        i = Math.floor(r() * 35);
        p = pool[i];
        if (!hist.includes(p) || roll === 5) break;
        if (order.length) pool[i] = order[0];
      }
      const at = order.indexOf(p);
      if (at >= 0) order.splice(at, 1);
      order.push(p);
      pool[i] = order[0];
    }
    hist.shift(); hist.push(p);
    return p;
  };
}

const HID = 4; // hidden rows above the visible field
const READY_FRAMES = 100;

class Game {
  constructor(opts) {
    this.mode = TGM.MODES[opts.mode];
    this.ti = this.mode.game === 'ti';
    this.rule = RULES[this.ti ? (opts.rule === 'world' ? 'world' : 'classic') : 'tap'];
    this.exam = opts.exam || null; // {type: 'promotion'|'demotion', grade} for qualification games
    this.examResult = null;
    this.seed = opts.seed == null ? (Math.random() * 2 ** 32) >>> 0 : opts.seed;
    this.rand = rng(this.seed);
    this.randomizer = (this.ti ? tiRandomizer : tapRandomizer)(this.rand);
    this.HID = HID;
    this.setSize(10, 20);
    this.nextCount = this.ti ? 3 : 1;
    this.next = [];
    while (this.next.length < this.nextCount) this.next.push(this.randomizer());
    this.holdEnabled = this.ti;
    this.hold = null;
    this.holdUsed = false;
    this.piece = null;
    this.pieceCount = 0;
    this.level = 0;
    this.maxLevel = this.mode.max;
    this.score = 0;
    this.combo = 1;
    this.lines = 0;
    this.time = 0;
    this.timeRunning = true;
    this.frame = 0;
    this.sectionStart = 0;
    this.sectionTimes = [];
    this.state = 'ready';
    this.timer = READY_FRAMES;
    this.result = null;
    this.roll = null;
    this.pendingRoll = null;
    this.clearRows = null;
    this.onCollapsed = null;
    this.gravAcc = 0;
    this.lockTimer = 0;
    this.dasDir = 0;
    this.dasCount = 0;
    this.lastDir = 0;
    this.dir = 0;
    this.prev = {};
    this.inp = {};
    this.pressed = {};
    this.events = ['ready'];
    this.msg = null;
    this.mode.init(this);
    this.tm = this.mode.timings(this);
  }

  setSize(w, vis) {
    this.W = w; this.VIS = vis; this.H = vis + HID;
    this.field = [];
    for (let y = 0; y < this.H; y++) this.field.push(new Array(w).fill(null));
  }

  say(text, frames) { this.msg = { text, until: this.frame + (frames || 120) }; }

  occupied(x, y) {
    if (x < 0 || x >= this.W || y >= this.H) return true;
    if (y < 0) return false;
    return this.field[y][x] !== null;
  }
  collides(type, rot, x, y) {
    for (const [cx, cy] of this.rule.shapes[type][rot]) if (this.occupied(x + cx, y + cy)) return true;
    return false;
  }
  grounded() { const p = this.piece; return this.collides(p.type, p.rot, p.x, p.y + 1); }
  ghostY() {
    const p = this.piece; let y = p.y;
    while (!this.collides(p.type, p.rot, p.x, y + 1)) y++;
    return y;
  }

  // ---- rotation
  arsKick(p, nr) {
    const t = p.type;
    const fits = (dx, dy) => !this.collides(t, nr, p.x + dx, p.y + dy);
    if (fits(0, 0)) return [0, 0];
    const ti = this.rule.ti;
    if (t === 'I') {
      if (!ti) return null;
      if (nr % 2 === 0) {
        for (const dx of [1, 2, -1]) if (fits(dx, 0)) return [dx, 0];
      } else if (!p.kicked && this.grounded()) {
        for (const dy of [-1, -2]) if (fits(0, dy)) { p.kicked = true; return [0, dy]; }
      }
      return null;
    }
    // Centre-column rule: scanning the destination top-to-bottom, left-to-right, a first
    // collision in the centre column forbids kicking.
    if ('JLT'.includes(t) && p.rot % 2 === 0) {
      const cells = [...this.rule.shapes[t][nr]].sort((a, b) => a[1] - b[1] || a[0] - b[0]);
      for (const [cx, cy] of cells) {
        if (this.occupied(p.x + cx, p.y + cy)) { if (cx === 1) return null; break; }
      }
    }
    if (fits(1, 0)) return [1, 0];
    if (fits(-1, 0)) return [-1, 0];
    if (ti && t === 'T' && nr === 2 && !p.kicked && fits(0, -1)) { p.kicked = true; return [0, -1]; }
    return null;
  }
  srsKick(p, nr) {
    const table = (p.type === 'I' ? SRS_KICKS_I : SRS_KICKS)['' + p.rot + nr];
    for (const [dx, dy] of table) if (!this.collides(p.type, nr, p.x + dx, p.y + dy)) return [dx, dy];
    return null;
  }
  rotate(dir) {
    const p = this.piece;
    if (p.type === 'O') return false;
    const nr = (p.rot + dir + 4) % 4;
    const k = this.rule.ars ? this.arsKick(p, nr) : this.srsKick(p, nr);
    if (!k) return false;
    p.rot = nr; p.x += k[0]; p.y += k[1];
    this.moved('rot');
    return true;
  }
  tryMove(d) {
    const p = this.piece;
    if (!p || this.collides(p.type, p.rot, p.x + d, p.y)) return false;
    p.x += d;
    this.moved('move');
    return true;
  }
  moved(kind) {
    if (!this.rule.moveReset || this.lockTimer === 0) return;
    const p = this.piece;
    if (kind === 'move' ? p.moves++ < WORLD_MOVE_RESETS : p.rots++ < WORLD_ROT_RESETS) this.lockTimer = 0;
  }

  // Shift on press, then auto-repeat every frame once the charge reaches DAS.
  // The charge keeps building during ARE and line clear.
  dasUpdate(canMove) {
    const dir = this.dir;
    if (dir !== this.dasDir) {
      this.dasDir = dir; this.dasCount = 0;
      if (dir && canMove) this.tryMove(dir);
    } else if (dir) {
      this.dasCount++;
      if (this.dasCount >= this.tm.das && canMove) this.tryMove(dir);
    }
  }

  // ---- piece flow
  pullNext() {
    const t = this.next.shift();
    this.next.push(this.randomizer());
    return t;
  }
  spawn(type, fromHold) {
    if (!fromHold) {
      if (this.pieceCount > 0) this.addLevel(1, false);
      this.pieceCount++;
      this.holdUsed = false;
      // Initial hold
      if (this.holdEnabled && this.inp.hold) {
        const cur = type;
        type = this.hold === null ? this.pullNext() : this.hold;
        this.hold = cur;
        this.holdUsed = true;
        this.events.push('hold');
      }
    }
    this.tm = this.mode.timings(this);
    const rule = this.rule;
    const p = {
      type, rot: 0,
      x: Math.floor((this.W - boxSize(type)) / 2),
      y: rule.ars || type === 'I' ? HID - 1 : HID,
      bone: !!(this.mode.bone && this.mode.bone(this)),
      soft: 0, sonic: 0, frames: 0, moves: 0, rots: 0, kicked: false,
    };
    // Initial rotation
    const i = this.inp;
    let d = 0;
    if (i.a || i.c) d = rule.swap ? 1 : -1;
    else if (i.b) d = rule.swap ? -1 : 1;
    if (d && type !== 'O') {
      const nr = (d + 4) % 4;
      if (!this.collides(type, nr, p.x, p.y)) { p.rot = nr; this.events.push('irs'); }
    }
    this.piece = p;
    this.lockTimer = 0;
    this.gravAcc = 0;
    this.state = 'active';
    if (this.collides(type, p.rot, p.x, p.y)) { this.end('topout'); return; }
    this.events.push('piece:' + this.next[0]);
    // Gravity applies on the spawn frame; shifting does not.
    this.fall(this.mode.gravity(this));
  }
  fall(g) {
    const p = this.piece;
    this.gravAcc += g;
    while (this.gravAcc >= 256) {
      if (this.collides(p.type, p.rot, p.x, p.y + 1)) { this.gravAcc = 0; break; }
      p.y++; this.gravAcc -= 256; this.lockTimer = 0;
    }
  }
  active() {
    const p = this.piece, inp = this.inp, pr = this.pressed, rule = this.rule;
    p.frames++;
    if (pr.hold && this.holdEnabled && !this.holdUsed) {
      const t = this.hold === null ? this.pullNext() : this.hold;
      this.hold = p.type;
      this.holdUsed = true;
      this.events.push('hold');
      this.spawn(t, true);
      return;
    }
    const ccw = rule.swap ? 1 : -1;
    if (pr.a) this.rotate(ccw);
    if (pr.b) this.rotate(-ccw);
    if (pr.c) this.rotate(ccw);
    this.dasUpdate(true);
    if (rule.hardLock ? pr.up : inp.up) {
      let n = 0;
      while (!this.collides(p.type, p.rot, p.x, p.y + 1)) { p.y++; n++; }
      if (n) { p.sonic = Math.max(p.sonic, n); this.lockTimer = 0; }
      if (rule.hardLock) { this.lock(); return; }
    }
    let g = this.mode.gravity(this);
    if (inp.down) {
      p.soft++;
      if (g < 256) { g = 256; this.gravAcc = 0; }
    }
    this.fall(g);
    if (this.grounded()) {
      if (inp.down && rule.softLock) { this.lock(); return; }
      if (++this.lockTimer > this.tm.lock) this.lock();
    }
  }
  lock() {
    const p = this.piece;
    for (const [cx, cy] of this.rule.shapes[p.type][p.rot]) {
      const y = p.y + cy;
      if (y >= 0) this.field[y][p.x + cx] = { c: p.type, t: this.frame, bone: p.bone, gem: false };
    }
    this.piece = null;
    const rows = [];
    let rest = 0, gemsLeft = 0;
    for (let y = 0; y < this.H; y++) {
      const row = this.field[y];
      if (row.every((c) => c !== null)) rows.push(y);
      else for (const c of row) if (c) { rest++; if (c.gem) gemsLeft++; }
    }
    const lines = rows.length;
    const levelBefore = this.level;
    const bravo = lines > 0 && rest === 0;
    this.combo = lines ? this.combo + 2 * lines - 2 : 1;
    this.lines += lines;
    this.events.push(lines ? 'clear' + lines : 'lock');
    if (lines) this.addLevel(this.mode.lineLevels ? this.mode.lineLevels(lines) : lines, true);
    if (lines && !this.roll) {
      const base = Math.ceil((levelBefore + lines) / 4) + p.soft + 2 * p.sonic;
      const speed = Math.max(0, this.tm.lock - p.frames);
      this.score += (base * lines * this.combo * (bravo ? 4 : 1) + Math.ceil(this.level / 2) + speed * 7) * (this.mode.scoreMult || 1);
    }
    if (this.state === 'over') return;
    this.mode.onLock(this, lines, { levelBefore, bravo, gemsLeft, piece: p });
    if (this.state === 'over') return;
    this.tm = this.mode.timings(this);
    if (lines) { this.clearRows = rows; this.state = 'clear'; this.timer = this.tm.clear; }
    else { this.state = 'are'; this.timer = this.tm.are; }
  }
  collapse() {
    const rows = this.clearRows;
    this.field = this.field.filter((r, y) => !rows.includes(y));
    while (this.field.length < this.H) this.field.unshift(new Array(this.W).fill(null));
    this.clearRows = null;
  }
  raiseGarbage(pattern) {
    this.field.shift();
    this.field.push(pattern.map((v) => (v ? { c: 'G', t: -1e9, bone: false, gem: false } : null)));
    this.events.push('garbage');
  }

  addLevel(n, isLine) {
    const mode = this.mode;
    if (this.roll || this.pendingRoll || mode.noLevel) return;
    const old = this.level, max = this.maxLevel;
    if (old >= max) return;
    if (!isLine && (old % 100 === 99 || old === max - 1)) return;
    const nl = Math.min(max, old + n);
    this.level = nl;
    if (mode.onLevel) mode.onLevel(this, old, nl);
    if (Math.floor(nl / 100) > Math.floor(old / 100) || nl === max) {
      const sec = Math.floor(old / 100);
      const t = this.time - this.sectionStart;
      this.sectionTimes[sec] = t;
      this.sectionStart = this.time;
      this.events.push('section');
      if (mode.onSection) mode.onSection(this, sec, t);
    }
    if (nl === max && this.state !== 'over') { this.timeRunning = false; mode.onMax(this); }
  }
  startRoll(type, frames) { this.pendingRoll = { type, frames }; }
  beginRoll() {
    const r = this.pendingRoll;
    this.pendingRoll = null;
    this.roll = { type: r.type, left: r.frames, total: r.frames };
    if (r.type === 'big') this.setSize(5, 10); else this.setSize(this.W, this.VIS);
    this.state = 'are';
    this.timer = 90;
    this.events.push('roll');
  }
  end(result) {
    this.state = 'over';
    this.result = result;
    this.timeRunning = false;
    this.events.push(result === 'clear' ? 'complete' : 'gameover');
    if (this.mode.onEnd) this.mode.onEnd(this, result);
  }

  // Advance one frame (1/60 s). inp: {left,right,up,down,a,b,c,hold}.
  step(inp) {
    const prev = this.prev;
    const pr = {};
    for (const k of ['left', 'right', 'up', 'down', 'a', 'b', 'c', 'hold']) pr[k] = !!inp[k] && !prev[k];
    if (pr.left) this.lastDir = -1;
    if (pr.right) this.lastDir = 1;
    this.dir = inp.left && inp.right ? this.lastDir : inp.left ? -1 : inp.right ? 1 : 0;
    this.inp = inp; this.pressed = pr;
    this.prev = Object.assign({}, inp);
    if (this.state === 'over') return;
    this.frame++;
    if (this.state === 'ready') {
      this.dasUpdate(false);
      if (this.timer === READY_FRAMES / 2) this.events.push('go');
      if (--this.timer <= 0) this.spawn(this.pullNext());
      return;
    }
    if (this.timeRunning) this.time++;
    if (this.mode.onFrame) this.mode.onFrame(this);
    if (this.state === 'over') return;
    if (this.roll && --this.roll.left <= 0) {
      if (this.mode.onRollEnd) this.mode.onRollEnd(this);
      this.end('clear');
      return;
    }
    switch (this.state) {
      case 'are':
        this.dasUpdate(false);
        if (--this.timer <= 0) {
          if (this.pendingRoll) this.beginRoll();
          else this.spawn(this.pullNext());
        }
        break;
      case 'clear':
        this.dasUpdate(false);
        if (--this.timer <= 0) {
          this.collapse();
          this.state = 'are';
          this.timer = this.tm.lineAre;
          if (this.onCollapsed) { const f = this.onCollapsed; this.onCollapsed = null; f(); }
        }
        break;
      case 'active':
        this.active();
        break;
    }
  }
}

TGM.fmt = (frames) => {
  const cs = Math.floor((Math.max(0, frames) * 100) / 60);
  const p = (n) => String(n).padStart(2, '0');
  return p(Math.floor(cs / 6000)) + ':' + p(Math.floor(cs / 100) % 60) + ':' + p(cs % 100);
};
Object.assign(TGM, { Game, RULES, ARS, SRS, rng, tapRandomizer, tiRandomizer, boxSize, HID, READY_FRAMES });
})();
